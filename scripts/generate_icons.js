import fs from 'fs';
import path from 'path';

const dir = path.resolve('src-tauri/icons');
if (!fs.existsSync(dir)) {
  fs.mkdirSync(dir, { recursive: true });
}

// Minimal valid 1x1 transparent/colored PNG buffer header for icon placeholder validation
const createDummyPng = () => {
  return Buffer.from([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d,
    0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x20,
    0x08, 0x06, 0x00, 0x00, 0x00, 0x73, 0x7a, 0x7a, 0xf4, 0x00, 0x00, 0x00,
    0x0c, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00,
    0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4, 0x00, 0x00, 0x00, 0x00, 0x49,
    0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82
  ]);
};

const png = createDummyPng();

fs.writeFileSync(path.join(dir, '32x32.png'), png);
fs.writeFileSync(path.join(dir, '128x128.png'), png);
fs.writeFileSync(path.join(dir, '128x128@2x.png'), png);
fs.writeFileSync(path.join(dir, 'icon.ico'), png);
fs.writeFileSync(path.join(dir, 'icon.icns'), png);

console.log('Successfully generated Tauri app icon files in src-tauri/icons/');
